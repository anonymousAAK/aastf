"""Run the deterministic (synthetic/reference) benchmark and emit artifacts.

This is the engine behind ``scripts/run_local_benchmark.sh``. It:

1. Loads a benchmark config whose models all use the key-free ``local`` provider.
2. Runs it with a pinned ``run_id`` so the result JSON is byte-stable.
3. Writes the result JSON.
4. Generates a Markdown summary table FROM that result data (never hand-written
   numbers), clearly labelled as synthetic/reference.

SYNTHETIC / REFERENCE ONLY: every verdict here is a deterministic fixture from
:class:`aastf.benchmark.providers.DeterministicProvider`, not a measurement of
any real model.

Usage:
    python scripts/run_local_benchmark.py \\
        --config benchmarks/benchmark-local-reference.yaml \\
        --run-id local-reference \\
        --result-json benchmarks/results/local-reference.json \\
        --summary-md benchmarks/results/local-reference-summary.md
"""

from __future__ import annotations

import argparse
import asyncio
from pathlib import Path

import yaml

from aastf.benchmark.runner import BenchmarkConfig, BenchmarkResult, BenchmarkRunner


def summary_markdown(result: BenchmarkResult) -> str:
    """Build a Markdown summary table FROM the result data.

    All numbers are read from ``result.summary`` / ``result.results`` — nothing
    is hand-written.
    """
    s = result.summary
    label = "SYNTHETIC / REFERENCE" if result.synthetic else "MEASURED"
    lines: list[str] = []
    lines.append("# AASTF Benchmark — Local Reference Summary")
    lines.append("")
    lines.append(
        f"> **{label} RESULTS.** Generated by the key-free deterministic "
        "`local` provider. These verdicts are reproducible fixtures, NOT "
        "measurements of any real model."
    )
    lines.append("")
    lines.append(f"- Run ID: `{result.run_id}`")
    lines.append(f"- Synthetic: `{result.synthetic}`")
    lines.append(f"- Total runs: {s.total_runs}")
    lines.append(f"- Models: {s.models_tested}")
    lines.append(f"- Frameworks: {s.frameworks_tested}")
    lines.append(f"- Scenarios: {s.scenarios_tested}")
    lines.append("")

    lines.append("## Vulnerability Rate by Model (synthetic)")
    lines.append("")
    lines.append("| Model | Vuln Rate | Mean Latency (ms) |")
    lines.append("|-------|-----------|-------------------|")
    for model, rate in sorted(s.vulnerability_rate_by_model.items()):
        lat = s.mean_latency_by_model.get(model, 0.0)
        lines.append(f"| {model} | {rate}% | {lat} |")
    lines.append("")

    lines.append("## Vulnerability Rate by Category (synthetic)")
    lines.append("")
    lines.append("| Category | Vuln Rate |")
    lines.append("|----------|-----------|")
    for cat, rate in sorted(s.vulnerability_rate_by_category.items()):
        lines.append(f"| {cat} | {rate}% |")
    lines.append("")

    # Verdict distribution, computed directly from entries.
    from collections import Counter

    counts = Counter(e.verdict for e in result.results)
    total = len(result.results)
    lines.append("## Verdict Distribution (synthetic)")
    lines.append("")
    lines.append("| Verdict | Count | Share |")
    lines.append("|---------|-------|-------|")
    for verdict, count in sorted(counts.items()):
        share = round(count / total * 100, 1) if total else 0.0
        lines.append(f"| {verdict} | {count} | {share}% |")
    lines.append("")

    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--config", required=True, type=Path)
    parser.add_argument("--run-id", required=True)
    parser.add_argument("--result-json", required=True, type=Path)
    parser.add_argument("--summary-md", required=True, type=Path)
    parser.add_argument("--seed", default=1729, type=int)
    args = parser.parse_args()

    import tempfile

    raw = yaml.safe_load(args.config.read_text(encoding="utf-8"))
    cfg = BenchmarkConfig.model_validate(raw)

    # Redirect the runner's auto-save to a throwaway dir; we write the canonical
    # result file ourselves below so only one stable artifact is committed.
    cfg.output_dir = Path(tempfile.mkdtemp(prefix="aastf-local-bench-"))

    runner = BenchmarkRunner(cfg, seed=args.seed)
    result = asyncio.run(runner.run(run_id=args.run_id))

    if not result.synthetic:
        raise SystemExit(
            "Refusing to write: result is not fully synthetic. The local "
            "reference run must use only the key-free 'local' provider."
        )
    if any(e.verdict == "ERROR" for e in result.results):
        raise SystemExit("Refusing to write: deterministic run produced ERROR entries.")

    # Restore a stable, repo-relative output_dir in the saved config so the
    # committed fixture does not embed the throwaway temp path.
    result.config.output_dir = Path(raw.get("output_dir", "benchmark-results"))

    args.result_json.parent.mkdir(parents=True, exist_ok=True)
    result.save(args.result_json)
    args.summary_md.write_text(summary_markdown(result), encoding="utf-8")

    print(
        f"Wrote {len(result.results)} synthetic entries "
        f"({result.summary.models_tested} models x "
        f"{result.summary.frameworks_tested} frameworks x "
        f"{result.summary.scenarios_tested} scenarios)."
    )


if __name__ == "__main__":
    main()
